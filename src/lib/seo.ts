import type { Project } from '$lib/types';

/**
 * One place for every URL, id and string that ends up in a meta tag.
 *
 * Everything here is static: the site has no server data, no user accounts and no
 * analytics, so search metadata is a build-time concern rather than a request-time one.
 */
export const SITE = {
	url: 'https://www.ivaniliev.online',
	name: 'Ivan Iliev',
	tagline: 'browser games, a pixel-art pond, and tooling I use every day',
	description:
		'ICT student at HZ in Vlissingen. I build things that run in a browser: a pixel-art pond, a drift racer, a racing AI, and the tools I use to build them.',
	locale: 'en_GB',
	themeColor: '#070912',
	github: 'https://github.com/Vanishonko',
	linkedin: 'https://www.linkedin.com/in/ivan-iliev-931511221/',
	email: 'vanishonko@gmail.com'
} as const;

/** Absolute URL for a site path, always with the canonical host. */
export function absolute(path = '/') {
	return new URL(path, SITE.url).toString();
}

/** The 1200x630 social card for a page, generated by `scripts/generate-og.mjs`. */
export function socialImage(slug = 'home') {
	return absolute(`/og/${slug}.png`);
}

/** Games live at two URLs (a write-up and a playable page) and must resolve to one entity. */
export function gameId(slug: string) {
	return `${SITE.url}/#game-${slug}`;
}

export type JsonLd = Record<string, unknown>;

